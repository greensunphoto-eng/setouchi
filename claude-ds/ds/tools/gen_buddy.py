#!/usr/bin/env python3
"""Generates the buddy (mascot) tiles and the menu icon.

The buddy is a 40x40 one-color pixel creature drawn with 5x5 tiles of 8x8.
Its two eye tiles come in five moods. Output:

  ../source/buddy_tiles.inc   designated initializers for glyph_bits[]
  ../icon.gif                 32x32 16-color icon for the flashcart menu

    python gen_buddy.py          # needs Pillow only for the icon
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIZE = 40
TILES = SIZE // 8

LEFT_EYE = (13, 20)
RIGHT_EYE = (27, 20)
EYE_TILES = ((1, 2), (3, 2))  # (tile x, tile y) holding the eyes
MOODS = ("open", "closed", "happy", "surprised", "dead")


def body(x, y):
    cx, cy, rx, ry = 19.5, 23.0, 17.0, 12.5
    if (abs(x - cx) / rx) ** 2.4 + (abs(y - cy) / ry) ** 2.4 <= 1.0:
        return True
    for ear_x in (11, 28):  # ears: triangles with the tip at y=4
        if 4 <= y <= 13 and abs(x - ear_x) <= (y - 4) * 4.5 / 9:
            return True
    if 35 <= y <= 37 and (9 <= x <= 14 or 25 <= x <= 30):  # feet
        return True
    return False


MOUTH = {(17, 26), (18, 27), (19, 27), (20, 27), (21, 27), (22, 26)}


def eye_holes(mood, ex, ey):
    """Pixels cut out of the body for one eye (they show the background)."""
    holes = set()
    if mood == "open":
        holes = {(x, y) for x in range(ex - 2, ex + 2) for y in range(ey - 2, ey + 3)}
        holes.discard((ex - 1, ey - 1))  # little highlight
    elif mood == "closed":
        holes = {(x, ey + 1) for x in range(ex - 2, ex + 2)}
    elif mood == "happy":
        holes = {(ex - 1, ey), (ex, ey), (ex - 2, ey + 1), (ex + 1, ey + 1),
                 (ex - 3, ey + 2), (ex + 2, ey + 2)}
    elif mood == "surprised":
        holes = {(x, y) for x in range(ex - 2, ex + 3) for y in range(ey - 3, ey + 3)}
        for corner in ((ex - 2, ey - 3), (ex + 2, ey - 3), (ex - 2, ey + 2), (ex + 2, ey + 2)):
            holes.discard(corner)
    elif mood == "dead":
        for i in range(5):
            holes.add((ex - 2 + i, ey - 2 + i))
            holes.add((ex + 2 - i, ey - 2 + i))
    return holes


def pixels(mood):
    holes = MOUTH | eye_holes(mood, *LEFT_EYE) | eye_holes(mood, *RIGHT_EYE)
    return [[body(x, y) and (x, y) not in holes for x in range(SIZE)] for y in range(SIZE)]


def tile_rows(px, tx, ty):
    rows = []
    for y in range(8):
        bits = 0
        for x in range(8):
            if px[ty * 8 + y][tx * 8 + x]:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def c_rows(rows):
    return "{ " + ", ".join("0x%02X" % r for r in rows) + " }"


def write_inc(path):
    base = pixels("open")
    lines = ["// Generated by tools/gen_buddy.py - do not edit.", ""]
    for ty in range(TILES):
        for tx in range(TILES):
            n = ty * TILES + tx
            lines.append("[G_BUDDY0 - GLYPH_FIRST + %2d] = %s," % (n, c_rows(tile_rows(base, tx, ty))))
    for m, mood in enumerate(MOODS):
        px = pixels(mood)
        for side, (tx, ty) in enumerate(EYE_TILES):
            lines.append("[G_EYES0 - GLYPH_FIRST + %2d] = %s, // %s %s" % (
                m * 2 + side, c_rows(tile_rows(px, tx, ty)), mood, "left" if side == 0 else "right"))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(path)


def write_icon(path):
    from PIL import Image  # only needed for the icon

    navy, orange, shadow = (8, 16, 41), (255, 131, 49), (190, 90, 30)
    px = pixels("open")
    img = Image.new("RGB", (32, 32), navy)
    out = img.load()
    for y in range(32):
        for x in range(32):
            sx, sy = x * SIZE // 32, y * SIZE // 32
            if px[sy][sx]:
                out[x, y] = orange
            elif body(sx, sy) and sy > 30:
                out[x, y] = shadow
    # Bright eyes so they read at icon size.
    for ex, ey in (LEFT_EYE, RIGHT_EYE):
        for dx in range(-2, 2):
            for dy in range(-2, 3):
                x, y = (ex + dx) * 32 // SIZE, (ey + dy) * 32 // SIZE
                out[x, y] = (255, 255, 255)
    img.convert("P", palette=Image.ADAPTIVE, colors=16).save(path)
    print(path)


def preview(mood="open"):
    for row in pixels(mood):
        print("".join("#" if p else "." for p in row))


if __name__ == "__main__":
    if "--preview" in sys.argv:
        preview(sys.argv[-1] if sys.argv[-1] in MOODS else "open")
        sys.exit(0)
    write_inc(os.path.join(HERE, "..", "source", "buddy_tiles.inc"))
    write_icon(os.path.join(HERE, "..", "icon.gif"))
